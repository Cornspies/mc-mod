package com.cornspies.fusionfactions.industry;

import com.cornspies.fusionfactions.FusionFactions;

import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.tags.TagKey;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.levelgen.feature.Feature;
import net.minecraft.world.level.levelgen.placement.PlacedFeature;
import net.neoforged.neoforge.common.world.BiomeModifier;
import net.neoforged.neoforge.registries.NeoForgeRegistries;

// The four ores of Phase 3 (D69, DESIGN.md §6b.2). Each one generates where its biome tag
// fusionfactions:has_ore/<ore> says: bauxite and niter in the whole overworld, rare earth only in mountains, lithium
// only in deserts and badlands. Servers can change the tags, or replace the features, with a datapack. The features
// themselves are generated by client.datagen.ModWorldGen.
public enum Ores {
    BAUXITE("bauxite"),
    NITER("niter"),
    RARE_EARTH("rare_earth"),
    LITHIUM("lithium");

    private final String name;

    Ores(String name) {
        this.name = name;
    }

    public String oreName() {
        return this.name;
    }

    public ResourceKey<Feature> feature() {
        return ResourceKey.create(Registries.FEATURE, FusionFactions.id("ore_" + this.name));
    }

    public ResourceKey<PlacedFeature> placedFeature() {
        return ResourceKey.create(Registries.PLACED_FEATURE, FusionFactions.id("ore_" + this.name));
    }

    public ResourceKey<BiomeModifier> biomeModifier() {
        return ResourceKey.create(NeoForgeRegistries.Keys.BIOME_MODIFIERS, FusionFactions.id("add_ore_" + this.name));
    }

    // The biomes this ore generates in.
    public TagKey<Biome> biomes() {
        return TagKey.create(Registries.BIOME, FusionFactions.id("has_ore/" + this.name));
    }
}
